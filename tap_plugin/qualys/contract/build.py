"""Regenerate ``extract.json`` from the committed DTDs, or check it (req-qualys-contract-extract-1).

``python -m tap_plugin.qualys.contract.build`` rewrites the extract; ``--check`` exits non-zero when the
committed extract differs from what the committed sources reduce to. The extract is generated, never typed.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

from tap_plugin.qualys.contract.reduce import reduce

HERE = Path(__file__).resolve().parent
VENDOR = HERE.parent / "tests" / "vendor"


def build() -> dict:
    consumed = json.loads((HERE / "consumed.json").read_text(encoding="utf-8"))
    documents = {}
    for key, doc in consumed["documents"].items():
        text = (VENDOR / doc["dtd"]).read_text(encoding="utf-8")
        documents[key] = {
            "description": doc["description"],
            "root": doc["root"],
            "source": {"dtd": doc["dtd"], "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest()},
            "elements": reduce(text, doc["elements"], doc.get("named_not_declared")),
        }
    return {
        "description": "Generated by contract/build.py from tests/vendor/*.dtd and contract/consumed.json; do not edit. For each document: its root element and, for every element this plugin reads, the DTD's content model, the children it requires, and its attributes.",
        "documents": documents,
    }


def render() -> str:
    return json.dumps(build(), indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if extract.json is out of date")
    args = parser.parse_args(argv)
    target = HERE / "extract.json"
    fresh = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != fresh:
            print("extract.json is out of date; run python -m tap_plugin.qualys.contract.build", file=sys.stderr)
            return 1
        return 0
    target.write_text(fresh, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
